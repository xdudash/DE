import type { Metadata, Viewport } from "next";
import { IBM_Plex_Sans, IBM_Plex_Serif } from "next/font/google";
import { ServiceWorkerRegistration } from "../components/ServiceWorkerRegistration";
import "./globals.css";

/**
 * One superfamily: the sans carries the interface in Latin and Cyrillic, the serif
 * sets German example sentences so they read as specimens rather than UI text.
 * next/font downloads these at build time and serves them from our own origin, so
 * no learner's browser makes a request to a font host.
 */
const sans = IBM_Plex_Sans({
  subsets: ["latin", "latin-ext", "cyrillic"],
  weight: ["400", "500", "600", "700"],
  variable: "--font-sans",
  display: "swap",
});
const serif = IBM_Plex_Serif({
  // German is Latin-only, so the serif does not need the Cyrillic subset.
  subsets: ["latin", "latin-ext"],
  weight: ["400", "600"],
  variable: "--font-serif",
  display: "swap",
});

export const metadata: Metadata = {
  title: { default: "DeutschGo", template: "%s · DeutschGo" },
  description: "German for life, work and study.",
  applicationName: "DeutschGo",
  // The manifest itself is generated by app/manifest.ts from lib/pwa/manifest.ts.
  manifest: "/manifest.webmanifest",
  icons: {
    icon: [
      { url: "/icons/icon-192.png", sizes: "192x192", type: "image/png" },
      { url: "/icons/icon-512.png", sizes: "512x512", type: "image/png" },
    ],
    apple: [{ url: "/icons/apple-touch-icon.png", sizes: "180x180", type: "image/png" }],
  },
  appleWebApp: { capable: true, title: "DeutschGo", statusBarStyle: "default" },
  formatDetection: { telephone: false },
};

export const viewport: Viewport = {
  width: "device-width",
  initialScale: 1,
  // Lay out under the notch and the home indicator; the CSS adds safe-area padding.
  viewportFit: "cover",
  // The browser bar blends with the page, so it follows the page background rather
  // than the brand colour (which the manifest uses for the install splash).
  themeColor: [
    { media: "(prefers-color-scheme: light)", color: "#ffffff" },
    { media: "(prefers-color-scheme: dark)", color: "#11161d" },
  ],
};

export default function RootLayout({ children }: { children: React.ReactNode }) {
  return (
    <html lang="en" className={`${sans.variable} ${serif.variable}`}>
      <body>
        {children}
        <ServiceWorkerRegistration />
      </body>
    </html>
  );
}
